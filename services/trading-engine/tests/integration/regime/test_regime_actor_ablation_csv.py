def _load_bars(fixture_name: str, bar_type: BarType) -> list[Bar]:
    """Read an OHLCV fixture CSV into Nautilus ``Bar`` objects.

    Prices/volumes are stored as their exact serialised strings so
    ``Price.from_str`` round-trips them without precision drift — the bars
    the real ``FeatureExtractor`` sees are byte-identical to the ones the
    generator classified when the recipe was tuned.
    """
    path = FIXTURES / f"{fixture_name}.csv"
    bars: list[Bar] = []
    with path.open(encoding="utf-8") as f:
        non_comment = (line for line in f if not line.lstrip().startswith("#"))
        for row in csv.DictReader(non_comment):
            ts = int(row["ts_init"])
            bars.append(
                Bar(
                    bar_type=bar_type,
                    open=Price.from_str(row["open"]),
                    high=Price.from_str(row["high"]),
                    low=Price.from_str(row["low"]),
                    close=Price.from_str(row["close"]),
                    volume=Quantity.from_str(row["volume"]),
                    ts_event=ts,
                    ts_init=ts,
                )
            )
    assert len(bars) == EXPECTED_BARS, (
        f"fixture {fixture_name}.csv parsed {len(bars)} bars, expected "
        f"{EXPECTED_BARS} — truncated CSV or a stray '#'-prefixed header row"
    )
    return bars


# ---------------------------------------------------------------------------
# Harness — one real backtest, return the strategy's order count
# ---------------------------------------------------------------------------


def _run_order_count(
    *,
    strategy_name: str,
    bars: list[Bar],
    bar_type: BarType,
    instrument: Instrument,
    regime_on: bool,
) -> int:
    """Run one real backtest and return the number of orders the strategy made.

    Mirrors ``runner_facade.run_backtest``'s regime wiring (attach the actor
    BEFORE the strategy, inject the SAME ``RegimeStateStore`` + the declared
    allow-list as runtime attributes) but drives custom fixture bars via
    ``add_data`` — the same direct-``BacktestRunner`` composition story 15.4
    used for the ordering spike. A blocked strategy never reaches its entry
    seam, so it submits zero orders (no entry => no bracket legs).
    """
    runner = BacktestRunner(
        config=BacktestRunnerConfig(
            strategy_name=strategy_name,
            initial_balance=Decimal("100000"),
            currency="USD",
        )
    )
    try:
        runner.add_venue(
            venue=instrument.id.venue,
            oms_type=OmsType.NETTING,
            account_type=AccountType.MARGIN,
            starting_balances=[Money(100_000, USD)],
            base_currency=USD,
        )
        runner.add_instrument(instrument)
        runner.add_data(bars)

        store: RegimeStateStore | None = None
        if regime_on:
            store = RegimeStateStore()
            runner.attach_regime(
                regime_config=_regime_config(),
                bar_type=bar_type,
                regime_state=store,
            )

        strategy = _build_strategy(
            strategy_name=strategy_name,
            instrument=instrument,
            bar_type=bar_type,
            params={},
        )
        if store is not None:
            strategy._regime_state = store
            strategy._allowed_regimes = _TEST_ALLOW_LISTS[strategy_name]
        runner.add_strategy(strategy)

        runner.run()
        return len(runner.engine.cache.orders())
    finally:
        runner.dispose()


