"""Story 15.9 — regime ablation harness on a real ``BacktestRunner``.

Ports ``test_router_ablation_csv.py`` (story 12.9) off the never-wired
``RegimeAwareRouter`` onto the production ``RegimeActor`` path (stories
15.5-15.8). Where the old test injected pre-computed ``RegimeFeatures``
through a scripted extractor and counted *dispatches* on a mock inner
router, this test feeds **OHLCV bar fixtures through the real
``FeatureExtractor``** on a real Nautilus ``BacktestEngine`` and counts the
strategy's *orders* — the only observable that proves the 15.7 entry gate
filters trades end to end.

Ablation matrix (allow-lists pinned test-locally in ``_TEST_ALLOW_LISTS``
— Track 2.1 archived ``bollinger_mean_reversion`` with ``regimes=[]``, but
it remains the ideal RANGING gate *vehicle* here because the fixtures were
tuned to its band-touch entries; the pin restores its historical allow-list
for gate-mechanics testing without depending on roster policy):

    donchian_breakout      -> {TRENDING_UP, TRENDING_DOWN}
    bollinger_mean_reversion -> {RANGING}   (pinned; archived in roster)

    fixture            allowed strategy           blocked strategy
    -----------------  -------------------------  ------------------------
    trending_up        donchian (enters)          bollinger (0 orders)
    trending_down      donchian (enters)          bollinger (0 orders)
    ranging            bollinger (enters)         donchian  (0 orders)
    high_volatility    -- kill-switch: both 0 --

"Has teeth" = the blocked strategy submits **zero** orders. Where the
blocked strategy *would* trade with the gate off (``ranging`` -> donchian,
``high_volatility`` -> both), the ON==0 / OFF>0 contrast proves the zero
comes from the regime gate, not from a mere absence of entry signal.

R2 (design ``regime-actor-design.md`` §risk R2 — warmup delta, MEDIUM)
========================================================================
The legacy router suppressed *dispatch*: a bar classified into a regime a
strategy did not allow (or any bar during warmup) never reached that
strategy's ``on_bar`` at all. The actor model is different and this test
pins the difference:

* The ``RegimeActor`` and the strategy both subscribe to the bar stream
  independently, so the strategy's ``on_bar`` **runs for every bar**,
  including the warmup window and blocked-regime bars. Its indicators
  advance; only the *entry seam* (``BaseStrategy._regime_admits``) is gated.
* During warmup the shared ``RegimeStateStore`` has no confirmed snapshot
  (``current() is None``) so ``_regime_admits`` returns ``False`` and entries
  are suppressed — but exits are never gated (R-A).

Net effect: entries the gate-off run would have opened during the warmup /
unconfirmed window are suppressed, so ``orders_on <= orders_off`` for an
allowed strategy. That non-negative gap **is** the warmup delta. It is
strictly more conservative than the router (fewer entries, never more), so
it is FTMO-safe — see ``test_warmup_delta_is_conservative``.

Fixtures are regenerated by ``fixtures/_generate_fixtures.py``; each carries
an inline recipe header. UNKNOWN is not exercised: the rule-based
classifier never emits it post-warmup for these streams, and the
``None``-snapshot suppression path is unit-tested in
``tests/unit/strategies/test_base_strategy_regime_gate.py``.
"""

