# Fixture integrity — pin each stream's confirmed regime to its intent
# ---------------------------------------------------------------------------


def _confirmed_tail_states(bars: list[Bar], bar_type: BarType) -> list[RegimeState]:
    """Replay the bars through the real actor pipeline; return confirmed states.

    Mirrors ``RegimeActor.on_bar`` exactly — same ``build_extractor`` wiring,
    the same ``RuleBasedRegimeClassifier`` + ``HysteresisFilter`` the factory
    builds — so this is what the shared ``RegimeStateStore`` would hold each
    bar. Only post-warmup bars (those that emit features) are returned.
    """
    cfg = _regime_config()
    instrument_cfg = cfg.instruments["XAUUSD"]
    extractor = build_extractor(str(bar_type), instrument_cfg, cfg.warmup_bars)
    classifier = RuleBasedRegimeClassifier(_thresholds())
    hysteresis = HysteresisFilter(
        bar_type=str(bar_type),
        confirmation_bars=cfg.confirmation_bars,
        thresholds=_thresholds(),
    )
    states: list[RegimeState] = []
    for bar in bars:
        features = extractor.update(bar)
        if features is None:
            continue
        ts = datetime.fromtimestamp(bar.ts_event / 1e9, tz=UTC)
        raw = classifier.decide(features)
        states.append(hysteresis.apply(raw, ts, features).current_state)
    return states


# Per fixture: the regime the allowed strategy needs to see, plus the regimes
# that MUST NOT appear in the confirmed tail because they would open the
# *blocked* strategy's gate and make its zero-order result a false negative.
#   donchian allows {TRENDING_UP, TRENDING_DOWN}; bollinger allows {RANGING}.
_TAIL = 80
_FIXTURE_REGIME_INTENT = {
    "trending_up": (
        RegimeState.TRENDING_UP,
        {RegimeState.RANGING},  # would open bollinger (the blocked strategy)
    ),
    "trending_down": (
        RegimeState.TRENDING_DOWN,
        {RegimeState.RANGING},  # would open bollinger
    ),
    "ranging": (
        RegimeState.RANGING,
        {RegimeState.TRENDING_UP, RegimeState.TRENDING_DOWN},  # would open donchian
    ),
    "high_volatility": (
        RegimeState.HIGH_VOLATILITY,
        # ANY tradable regime would open one of the two gates the kill-switch
        # is supposed to override.
        {RegimeState.TRENDING_UP, RegimeState.TRENDING_DOWN, RegimeState.RANGING},
    ),
}


@pytest.mark.parametrize("fixture_name", list(_FIXTURE_REGIME_INTENT))
def test_fixture_confirmed_regime_matches_intent(
    fixture_name: str,
    _instrument_and_bar_type: tuple[Instrument, BarType],
) -> None:
    """Each fixture's confirmed-tail regime is its intended one, and contains
    no regime that would open the blocked strategy's gate.

    This decouples the ablation assertions from the strategies' own signal
    logic: it proves the zero-order results above come from the regime the
    gate sees (e.g. bollinger is gated on a genuinely TRENDING tail, not merely
    signal-less), and it is the tripwire that fails loudly if a threshold change
    or a fixture regeneration drifts a stream out of its target regime.
    """
    _, bar_type = _instrument_and_bar_type
    bars = _load_bars(fixture_name, bar_type)
    intended, forbidden = _FIXTURE_REGIME_INTENT[fixture_name]

    tail = _confirmed_tail_states(bars, bar_type)[-_TAIL:]
    assert tail, f"{fixture_name}: no post-warmup bars to classify"

    counts = Counter(tail)
    assert counts[intended] > 0, (
        f"{fixture_name}: confirmed tail never reaches the intended "
        f"{intended.value}; distribution={ {s.value: n for s, n in counts.items()} }"
    )
    leaked = forbidden & set(tail)
    assert not leaked, (
        f"{fixture_name}: confirmed tail leaks {[s.value for s in leaked]}, "
        f"which would open the blocked strategy's gate and void the ablation; "
        f"distribution={ {s.value: n for s, n in counts.items()} }"
    )
