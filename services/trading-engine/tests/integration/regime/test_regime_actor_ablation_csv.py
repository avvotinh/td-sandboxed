# ``blocked_trades_with_gate_off`` marks the rows where the blocked strategy
# WOULD trade with the gate off, so its ON==0 is a true ablation "teeth"
# result. For the two trending rows it is False: a mean-reversion strategy
# produces no entry signal on a clean trend regardless of the gate, so
# bollinger's zero there is a *consistency* check, not a teeth proof. The
# teeth are proven by the ranging row (below) and ``high_volatility``; that
# bollinger is gated (not merely signal-less) on the trend streams is
# established separately by ``test_fixture_confirmed_regime_matches_intent``,
# which pins each fixture's confirmed regime to its intended value.
@pytest.mark.parametrize(
    "fixture_name, allowed, blocked, blocked_trades_with_gate_off",
    [
        ("trending_up", DONCHIAN, BOLLINGER, False),
        ("trending_down", DONCHIAN, BOLLINGER, False),
        ("ranging", BOLLINGER, DONCHIAN, True),
    ],
)
def test_regime_gate_routes_to_allowed_only(
    fixture_name: str,
    allowed: str,
    blocked: str,
    blocked_trades_with_gate_off: bool,
    _instrument_and_bar_type: tuple[Instrument, BarType],
) -> None:
    """Allowed strategy enters; the blocked strategy submits zero orders."""
    instrument, bar_type = _instrument_and_bar_type
    bars = _load_bars(fixture_name, bar_type)

    allowed_on = _run_order_count(
        strategy_name=allowed,
        bars=bars,
        bar_type=bar_type,
        instrument=instrument,
        regime_on=True,
    )
    blocked_on = _run_order_count(
        strategy_name=blocked,
        bars=bars,
        bar_type=bar_type,
        instrument=instrument,
        regime_on=True,
    )

    assert allowed_on > 0, (
        f"{allowed} should enter on a {fixture_name} stream whose confirmed "
        f"regime is in its allow-list; got {allowed_on} orders"
    )
    assert blocked_on == 0, (
        f"{blocked} should submit zero orders when {fixture_name}'s regime is "
        f"outside its allow-list (the ablation gate has no teeth otherwise); "
        f"got {blocked_on}"
    )

    if blocked_trades_with_gate_off:
        blocked_off = _run_order_count(
            strategy_name=blocked,
            bars=bars,
            bar_type=bar_type,
            instrument=instrument,
            regime_on=False,
        )
        assert blocked_off > 0, (
            f"{blocked} should trade on {fixture_name} with the regime gate "
            f"OFF — otherwise the ON==0 result is mere absence of signal, not "
            f"proof the gate suppressed entries; got {blocked_off}"
        )


def test_high_volatility_kills_every_strategy(
    _instrument_and_bar_type: tuple[Instrument, BarType],
) -> None:
    """HIGH_VOLATILITY is the global kill-switch — every strategy gets zero
    orders regardless of its allow-list, while each one trades with the gate
    off (so the zero is the kill-switch, not a dead market).
    """
    instrument, bar_type = _instrument_and_bar_type
    bars = _load_bars("high_volatility", bar_type)

    for name in (DONCHIAN, BOLLINGER):
        on = _run_order_count(
            strategy_name=name,
            bars=bars,
            bar_type=bar_type,
            instrument=instrument,
            regime_on=True,
        )
        off = _run_order_count(
            strategy_name=name,
            bars=bars,
            bar_type=bar_type,
            instrument=instrument,
            regime_on=False,
        )
        assert on == 0, (
            f"{name} must submit zero orders under HIGH_VOLATILITY "
            f"(global kill-switch); got {on}"
        )
        assert off > 0, (
            f"{name} should trade on the high-volatility stream with the gate "
            f"off — proves ON==0 is the kill-switch, not a dead market; "
            f"got {off}"
        )


def test_warmup_delta_is_conservative(
    _instrument_and_bar_type: tuple[Instrument, BarType],
) -> None:
    """R2: the actor model never opens *more* entries than the gate-off run.

    The strategy's ``on_bar`` runs through warmup in the actor model, but its
    entry seam is suppressed until the regime store holds a confirmed snapshot
    (and during any unconfirmed/blocked bar). So an allowed strategy can only
    place entries the gate-off run also placed minus those falling in the
    warmup/unconfirmed window: ``0 < orders_on <= orders_off``. The gap is the
    warmup delta — strictly conservative (fewer trades, never more), hence
    FTMO-safe.
    """
    instrument, bar_type = _instrument_and_bar_type
    bars = _load_bars("trending_up", bar_type)

    orders_on = _run_order_count(
        strategy_name=DONCHIAN,
        bars=bars,
        bar_type=bar_type,
        instrument=instrument,
        regime_on=True,
    )
    orders_off = _run_order_count(
        strategy_name=DONCHIAN,
        bars=bars,
        bar_type=bar_type,
        instrument=instrument,
        regime_on=False,
    )

    assert orders_on > 0, "allowed strategy should still trade with regime ON"
    assert orders_on <= orders_off, (
        "the actor-model warmup gate must never open MORE entries than the "
        f"gate-off run (R2 warmup delta is non-negative); on={orders_on} "
        f"off={orders_off}"
    )


